import { createHash } from 'node:crypto';
import { defineConfig } from 'vitest/config';
import { PREVIEW_STYLE } from './src/ui/preview-style.js';

/**
 * Content Security Policy for the built app.
 *
 * - Nothing is inline, so scripts and styles can be 'self' only.
 * - The one exception is the preview frame's <style>: a srcdoc frame inherits
 *   the page's policy, so that exact stylesheet is allowed by its hash,
 *   computed here from the same constant the app uses.
 * - data: images are needed for the select arrow (CSS) and harmless otherwise.
 */
const previewStyleHash = createHash('sha256').update(PREVIEW_STYLE).digest('base64');

export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self'",
  `style-src 'self' 'sha256-${previewStyleHash}'`,
  "img-src 'self' data:",
  "connect-src 'self'",
  "frame-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'none'",
].join('; ');

/**
 * Response headers for hosts that read a `_headers` file (Netlify, Cloudflare
 * Pages). Paths assume the app is served from the site root; see
 * docs/embedding.md when serving it from a sub-folder.
 */
const HEADERS_FILE = `# Generated by vite.config.js at build time. Edit it there, not here.
/*
  Content-Security-Policy: ${CONTENT_SECURITY_POLICY}; frame-ancestors 'self'
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;

/**
 * Production builds only: the dev server injects inline styles for hot
 * reloading, which this policy would (rightly) block.
 *
 * @returns {import('vite').Plugin}
 */
function securityHeaders() {
  return {
    name: 'entity-escaper:security-headers',
    apply: 'build',
    transformIndexHtml: {
      order: 'post',
      handler(html) {
        // Must come before anything that loads a resource, so straight after <meta charset>.
        return html.replace(
          /<meta charset="UTF-8" \/>/i,
          `$&\n    <meta http-equiv="Content-Security-Policy" content="${CONTENT_SECURITY_POLICY}" />`,
        );
      },
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: '_headers', source: HEADERS_FILE });
    },
  };
}

export default defineConfig({
  // Relative asset paths, so the build works at a domain root or in any
  // sub-folder (GitHub Pages project sites, a folder inside another site).
  base: './',
  plugins: [securityHeaders()],
  build: {
    outDir: 'dist',
    emptyOutDir: true,
  },
  test: {
    include: ['tests/**/*.test.js'],
    environment: 'node',
  },
});
